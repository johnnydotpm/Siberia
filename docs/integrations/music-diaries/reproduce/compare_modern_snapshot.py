"""Cross-check selected iOS strings in supplied Android serialized snapshot.

No execution/disassembly. Requires length-prefixed literal match, rather than
mistaking a route prefix found inside a longer route for a standalone literal.
Validated encoding: unsigned7-bit integer with high-bit terminal; value is
(UTF16 code-unit length <<1) | is_two_byte_string. Not a full snapshot parser.
"""
import hashlib
import json
import pathlib
import re
import argparse

OUT = pathlib.Path(__file__).resolve().parent
if OUT.name == "reproduce":
    OUT = OUT.parent
ROOT = OUT.parent / "extracted" / "mobireg-android-modern"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--android-carrier", type=pathlib.Path, default=ROOT / "config.arm64_v8a/lib/arm64-v8a/libapp.so")
parser.add_argument("--ios-full", type=pathlib.Path, default=OUT / "ios-dart-strings.json", help="Full iOS strings generated by extract_dart_strings.py; accepts list or object with strings")
parser.add_argument("--selected", type=pathlib.Path, default=OUT / "ios-selected-evidence.json")
parser.add_argument("--output", type=pathlib.Path, default=OUT / "modern-platform-comparison.json")
args = parser.parse_args()
carrier = args.android_carrier
data = carrier.read_bytes()
selected = json.loads(args.selected.read_text(encoding="utf8"))
ios_full = json.loads(args.ios_full.read_text(encoding="utf8"))
if isinstance(ios_full, dict):
    ios_full = ios_full["strings"]


def marker(value):
    result = bytearray()
    while value > 127:
        result.append(value & 127)
        value >>= 7
    result.append(value | 128)
    return bytes(result)


def locate(text, two_byte):
    raw = text.encode("utf-16le" if two_byte else "latin1")
    length = len(text.encode("utf-16le")) // 2
    prefix = marker((length << 1) | int(two_byte))
    position = data.find(prefix + raw)
    return position + len(prefix) if position >= 0 else None


matches = []
missing = []
variants = []
for row in selected["strings"]:
    text = row["text"]
    two_byte = row["cid"] == 95
    offset = locate(text, two_byte)
    if offset is not None:
        matches.append({"offset": hex(offset), "text": text,
                        "encoding": "utf-16le" if two_byte else "latin1",
                        "ios_offset": row["offset"],
                        "match": "exact literal with compact length/encoding marker"})
    else:
        missing.append({"text": text, "ios_offset": row["offset"]})
        if re.search(r"@\d+", text):
            pattern = re.escape(text)
            pattern = re.sub(r"@\d+", r"@\\d+", pattern).encode()
            found = re.search(pattern, data)
            if found:
                variants.append({"ios_text": text, "android_text": found.group().decode("latin1"),
                    "offset": hex(found.start()), "basis": "private symbol numeric suffix differs; behavior not compared"})

build = re.search(rb"Wersja 3\.1\.7 \(build 116, [0-9a-f]+\)", data)
result = {"evidence_id": "MR-M01", "source": "config.arm64_v8a/lib/arm64-v8a/libapp.so",
    "sha256": hashlib.sha256(data).hexdigest(), "size": len(data),
    "xapk_sha256": "a8ab26b4101507ce7e80f067ee135dc7632571facb26358042da02487b5010e7",
    "application_id": "pl.mobireg.eparent.music", "version_name": "3.1.7", "version_code": 116,
    "build_stamp": {"text": build.group().decode(), "offset": hex(build.start())} if build else None,
    "scope": f"All {len(selected['strings'])} selected iOS Dart literals; exact length-marker matches",
    "matches": matches, "not_exactly_found_in_android": missing, "private_symbol_variants": variants,
    "limitations": ["Partial serialized-snapshot scan, not a complete snapshot decoder",
        "String/model identity does not prove execution, matching call graph, wire contracts or runtime parity",
        "Missing literals may result from source revision, platform conditional compilation, symbols or encoding differences",
        "Android source revision6f4e7b8 differs from iOSd20dd8d despite same marketed version/build"]}


def independent_inventory(pattern):
    rows = []
    for match in re.finditer(pattern, data):
        raw = match.group()
        prefix = marker(len(raw) << 1)
        if data[match.start()-len(prefix):match.start()] != prefix:
            continue
        rows.append({"offset": hex(match.start()), "text": raw.decode("ascii"),
                     "match": "exact compact length marker; candidate scan"})
    return rows


android_sources = independent_inventory(rb"package:rodzic/[A-Za-z0-9_./]+\.dart")
ios_sources = [r for r in ios_full if r["text"].startswith("package:rodzic/") and r["text"].endswith(".dart")]
android_paths = independent_inventory(rb"/[A-Za-z0-9_./?=&<>:$#%+\-]{1,299}")
ios_paths = [r for r in ios_full if re.fullmatch(r"/[A-Za-z0-9_./?=&<>:$#%+\-]{1,299}", r["text"])]
for name, android_rows, ios_rows, scope in [
    ("full_app_owned_source_path_inventory", android_sources, ios_sources, "All exact package:rodzic/...dart candidate literals independently scanned in Android AOT versus full iOS structured-string set"),
    ("full_path_literal_inventory", android_paths, ios_paths, "All length-prefixed ASCII path-like candidate literals matching /[A-Za-z0-9_./?=&<>:$#%+-]{1,299}; includes UI, local, dependency paths and possible short false positives")]:
    android_set = {r["text"] for r in android_rows}
    ios_set = {r["text"] for r in ios_rows}
    result[name] = {"android": android_rows, "ios": ios_rows,
        "android_only": sorted(android_set-ios_set), "ios_only": sorted(ios_set-android_set),
        "shared": len(android_set&ios_set), "scope": scope}
args.output.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf8")
print(f"Exact matches={len(matches)}, not exact={len(missing)}, private variants={len(variants)}")
print(f"App-owned source paths Android={len(android_sources)}, iOS={len(ios_sources)}")
