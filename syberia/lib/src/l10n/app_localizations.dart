extension LocalizedError on BuildContext {
  /// Renders [error] in the current locale. Translating here rather than
  /// where the error is caught keeps an error already on screen correct
  /// after the user switches language.
  String trError(AppError error) {
    final code = error.errorCode;
    if (code == null) {
      final raw = error.raw?.trim();
      return raw == null || raw.isEmpty ? tr('unexpectedError') : raw;
    }
    final key = errorMessageKeys[code] ?? 'unexpectedError';
    final detail = error.detail;
    return detail == null ? tr(key) : trArgs(key, {'detail': detail});
  }
}
