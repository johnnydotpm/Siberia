#!/usr/bin/env python3
"""Trim the bundled fonts to the characters the app shows.

Run from syberia/ with the original font files. Each one given is trimmed
into assets/fonts, so any of them can be redone on its own:

    pip install fonttools
    python3 tool/subset_fonts.py \\
        --inter path/to/InterVariable.ttf \\
        --unbounded path/to/Unbounded.ttf \\
        --google-sans-flex 'path/to/GoogleSansFlex[ROND,opsz,slnt,wdth,wght].ttf' \\
        --symbols 'path/to/MaterialSymbolsRounded[FILL,GRAD,opsz,wght].ttf' \\
        --symbol-codepoints 'path/to/MaterialSymbolsRounded[FILL,GRAD,opsz,wght].codepoints'

Inter keeps Latin with its extensions (Polish), Cyrillic (Russian and
Ukrainian), punctuation, currency, arrows and common symbols. Unbounded only
draws the "SiberiaGB" wordmark, so it keeps basic Latin. Both stay variable
fonts with every weight.

Google Sans Flex, the Expressive design's typeface, keeps the same Latin as
Inter; it has no Cyrillic. It keeps its optical size and roundness axes and
the weights from 400 to 700, all the type scale uses; width and slant are
fixed at their defaults.

Material Symbols Rounded keeps only the icons the app uses: every
`Icons.name` in lib/ and the extras below. It keeps its fill and weight axes;
grade and optical size are fixed at 0 and 24. The same run writes
lib/src/theme/app_symbols.dart with those icons, so the two always match.
"""
import argparse
import keyword
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / 'assets/fonts'
SYMBOLS_DART = ROOT / 'lib/src/theme/app_symbols.dart'

LATIN = [
    'U+0000-024F', 'U+0259', 'U+02B0-02FF', 'U+0300-036F', 'U+1E9E',
    'U+2000-206F', 'U+20A0-20CF', 'U+2100-214F', 'U+2150-218F',
    'U+2190-21FF', 'U+2200-22FF', 'U+2300-23FF', 'U+25A0-25FF',
    'U+2600-26FF', 'U+2713-2717', 'U+FB01-FB02', 'U+FEFF', 'U+FFFD',
]
INTER = ','.join(LATIN + ['U+0400-052F'])
GOOGLE_SANS_FLEX = ','.join(LATIN)
UNBOUNDED = 'U+0020-007E'

# Material icon names whose symbol is called differently.
SYMBOL_RENAMES = {
    'copy': 'content_copy',
    'info_outline': 'info',
    'person_add_alt_1': 'person_add',
}
# Symbols the Expressive design uses that no `Icons.name` brings in.
SYMBOL_EXTRAS = [
    'arrow_back', 'calendar_month', 'check', 'close', 'expand_more', 'home',
    'mail', 'menu', 'palette', 'school',
]
DART_RESERVED = set(keyword.kwlist) | {
    'class', 'new', 'switch', 'default', 'case', 'enum', 'extends', 'final',
    'const', 'var', 'void', 'null', 'true', 'false', 'this', 'super', 'is',
    'in', 'do', 'if', 'for', 'try', 'catch', 'throw', 'rethrow', 'return',
    'while', 'with', 'assert', 'break', 'continue', 'else',
}


def run(*args):
    subprocess.run([sys.executable, '-m', *map(str, args)], check=True)


def subset(source, target, unicodes, *extra):
    run('fontTools.subset', source, f'--unicodes={unicodes}',
        '--name-IDs=*', '--name-languages=*', '--notdef-outline',
        f'--output-file={target}', *extra)


def material_names():
    """The Material icon names lib/ uses, without CupertinoIcons."""
    pattern = re.compile(r'(?<![A-Za-z_])Icons\.([a-z0-9_]+)')
    names = set()
    for path in (ROOT / 'lib').rglob('*.dart'):
        if path == SYMBOLS_DART:
            continue
        names.update(pattern.findall(path.read_text(encoding='utf-8')))
    return sorted(names)


def symbol_of(material):
    base = re.sub(r'_(rounded|outlined|sharp)$', '', material)
    return SYMBOL_RENAMES.get(base, base)


def dart_name(symbol):
    parts = symbol.split('_')
    name = parts[0] + ''.join(p[:1].upper() + p[1:] for p in parts[1:])
    if name[0].isdigit():
        name = 's' + name
    return name + '_' if name in DART_RESERVED else name


def write_symbols_dart(codepoints, materials):
    symbols = sorted({symbol_of(m) for m in materials} | set(SYMBOL_EXTRAS))
    missing = [s for s in symbols if s not in codepoints]
    if missing:
        sys.exit(f'No such symbols: {", ".join(missing)}. '
                 'Add them to SYMBOL_RENAMES.')
    lines = [
        '// Generated by tool/subset_fonts.py. Do not edit by hand: add',
        '// icons there and run it again, so the font keeps the same glyphs.',
        '',
        "import 'package:flutter/material.dart';",
        '',
        '/// Material Symbols Rounded, the icons of the Expressive design.',
        '///',
        '/// Each draws outlined; `Icon(symbol, fill: 1)` draws it filled, as',
        '/// the selected item of a bar or a group shows it.',
        'abstract final class AppSymbols {',
        "  static const fontFamily = 'MaterialSymbolsRounded';",
        '',
    ]
    for symbol in symbols:
        lines.append(
            f'  static const {dart_name(symbol)} = '
            f'IconData(0x{codepoints[symbol]}, fontFamily: fontFamily);')
    lines += [
        '',
        '  /// The symbol drawn in place of a Material icon the app uses.',
        '  static IconData? of(IconData icon) => _fromMaterial[icon];',
        '',
        '  static final Map<IconData, IconData> _fromMaterial = {',
    ]
    for material in materials:
        lines.append(f'    Icons.{material}: {dart_name(symbol_of(material))},')
    lines += ['  };', '}', '']
    SYMBOLS_DART.write_text('\n'.join(lines), encoding='utf-8')
    if shutil.which('dart'):
        subprocess.run(['dart', 'format', str(SYMBOLS_DART)], check=True,
                       stdout=subprocess.DEVNULL)
    else:
        print('Run dart format on lib/src/theme/app_symbols.dart.')
    return symbols


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    parser.add_argument('--inter', type=Path)
    parser.add_argument('--unbounded', type=Path)
    parser.add_argument('--google-sans-flex', type=Path)
    parser.add_argument('--symbols', type=Path)
    parser.add_argument('--symbol-codepoints', type=Path)
    args = parser.parse_args()
    if not any(vars(args).values()):
        parser.print_help()
        sys.exit(1)
    if bool(args.symbols) != bool(args.symbol_codepoints):
        sys.exit('--symbols and --symbol-codepoints go together.')

    if args.inter:
        subset(args.inter, FONTS / 'InterVariable.ttf', INTER,
               '--layout-features+=tnum,case,frac,sups,subs', '--glyph-names',
               '--symbol-cmap', '--legacy-cmap')
    if args.unbounded:
        subset(args.unbounded, FONTS / 'Unbounded.ttf', UNBOUNDED)
    with tempfile.TemporaryDirectory() as temp:
        if args.google_sans_flex:
            fixed = Path(temp) / 'gsf.ttf'
            run('fontTools.varLib.instancer', args.google_sans_flex,
                'slnt=0', 'wdth=100', 'wght=400:700', '-o', fixed)
            subset(fixed, FONTS / 'GoogleSansFlex.ttf', GOOGLE_SANS_FLEX,
                   '--layout-features+=tnum,case,frac,sups,subs')
        if args.symbols:
            codepoints = dict(
                line.split() for line in
                args.symbol_codepoints.read_text().splitlines() if line)
            symbols = write_symbols_dart(codepoints, material_names())
            fixed = Path(temp) / 'symbols.ttf'
            run('fontTools.varLib.instancer', args.symbols,
                'GRAD=0', 'opsz=24', '-o', fixed)
            subset(fixed, FONTS / 'MaterialSymbolsRounded.ttf',
                   ','.join(f'U+{codepoints[s]}' for s in symbols),
                   '--layout-features=', '--no-hinting')
            print(f'{len(symbols)} symbols.')
    print('Done.')


if __name__ == '__main__':
    main()
